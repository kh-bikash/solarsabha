"""Load the repo's .env into os.environ (without overriding variables already set). Used by the scripts."""
import os
from pathlib import Path

def load_env():
    env = Path(__file__).resolve().parents[1] / ".env"
    if not env.exists():
        return
    for line in env.read_text().splitlines():
        line = line.split("#", 1)[0].strip()
        if "=" in line:
            k, v = line.split("=", 1)
            os.environ.setdefault(k.strip(), v.strip())
